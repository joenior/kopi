insert into storage.buckets (id, name, public)
values ('menu-images', 'menu-images', true)
on conflict (id) do update set public = true;

-- 1. Akses Baca Publik (Wajib agar gambar menu tampil di browser pelanggan)
drop policy if exists "Menu images are publicly accessible" on storage.objects;
create policy "Menu images are publicly accessible"
on storage.objects for select
using (bucket_id = 'menu-images');

-- 2. Staf dan Owner upload gambar baru (INSERT)
drop policy if exists "Authenticated staff can upload menu images" on storage.objects;
create policy "Authenticated staff can upload menu images"
on storage.objects for insert
to authenticated
with check (
    bucket_id = 'menu-images' 
    and (select public.is_staff_or_owner())
);

-- 3. Staf dan Owner perbarui gambar / upsert (UPDATE)
drop policy if exists "Authenticated staff can update menu images" on storage.objects;
create policy "Authenticated staff can update menu images"
on storage.objects for update
to authenticated
using (
    bucket_id = 'menu-images' 
    and (select public.is_staff_or_owner())
)
with check (
    bucket_id = 'menu-images' 
    and (select public.is_staff_or_owner())
);

-- 4. Staf dan Owner hapus gambar (DELETE)
drop policy if exists "Authenticated staff can delete menu images" on storage.objects;
create policy "Authenticated staff can delete menu images"
on storage.objects for delete
to authenticated
using (
    bucket_id = 'menu-images' 
    and (select public.is_staff_or_owner())
);
