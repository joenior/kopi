-- 1. Staf toggle ketersediaan menu (Hanya boleh ubah kolom is_available)
create or replace function public.toggle_menu_availability(
    p_item_id text,
    p_is_available boolean
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_cafe_id text;
begin
    select cafe_id into v_cafe_id from public.menu_items where id = p_item_id;
    if not found then
        raise exception 'Menu item not found';
    end if;

    -- Validasi caller adalah staff atau owner dari kedai ini
    if not exists (
        select 1 from public.staff_memberships
        where user_id = (select auth.uid())
          and cafe_id = v_cafe_id
          and role in ('staff', 'owner')
    ) then
        raise exception 'Unauthorized: caller must be staff or owner of this cafe';
    end if;

    update public.menu_items
    set is_available = p_is_available,
        updated_at = now()
    where id = p_item_id;

    return true;
end;
$$;

-- 2. Alur Status Pesanan & Pembatalan (Perubahan status maju sesuai alur atau batal wajib alasan)
create or replace function public.advance_order_status(
    p_order_id text,
    p_next_status text,
    p_payment_method text default null,
    p_cancellation_reason text default null
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_current_status text;
    v_cafe_id text;
begin
    select status, cafe_id into v_current_status, v_cafe_id
    from public.orders
    where id = p_order_id;

    if not found then
        raise exception 'Order not found';
    end if;

    -- Validasi caller adalah staff atau owner dari kedai ini
    if not exists (
        select 1 from public.staff_memberships
        where user_id = (select auth.uid())
          and cafe_id = v_cafe_id
          and role in ('staff', 'owner')
    ) then
        raise exception 'Unauthorized: caller must be staff or owner of this cafe';
    end if;

    -- Validasi pembatalan
    if p_next_status = 'dibatalkan' then
        if p_cancellation_reason is null or trim(p_cancellation_reason) = '' then
            raise exception 'Cancellation requires a non-empty reason';
        end if;

        if v_current_status in ('selesai', 'dibatalkan') then
            raise exception 'Cannot cancel an order that is already completed or cancelled';
        end if;

        update public.orders
        set status = 'dibatalkan',
            cancellation_reason = p_cancellation_reason,
            updated_at = now()
        where id = p_order_id;

        insert into public.order_status_logs (order_id, from_status, to_status, changed_by, reason)
        values (p_order_id, v_current_status, 'dibatalkan', (select auth.uid()), p_cancellation_reason);

        return true;
    end if;

    -- Validasi alur maju: baru -> diproses -> siap -> selesai
    if (v_current_status = 'baru' and p_next_status = 'diproses') or
       (v_current_status = 'diproses' and p_next_status = 'siap') then
        update public.orders
        set status = p_next_status,
            updated_at = now()
        where id = p_order_id;

        insert into public.order_status_logs (order_id, from_status, to_status, changed_by)
        values (p_order_id, v_current_status, p_next_status, (select auth.uid()));

        return true;
    elsif (v_current_status = 'siap' and p_next_status = 'selesai') then
        -- Penyelesaian pesanan sekaligus pencatatan pembayaran manual
        if p_payment_method not in ('tunai', 'qris', 'transfer') then
            raise exception 'Penyelesaian pesanan wajib mencatat metode pembayaran (tunai, qris, transfer)';
        end if;

        update public.orders
        set status = 'selesai',
            payment_status = 'lunas',
            payment_method = p_payment_method,
            updated_at = now()
        where id = p_order_id;

        insert into public.order_status_logs (order_id, from_status, to_status, changed_by, reason)
        values (p_order_id, v_current_status, 'selesai', (select auth.uid()), 'Lunas via ' || p_payment_method);

        return true;
    else
        raise exception 'Invalid status transition from % to %', v_current_status, p_next_status;
    end if;
end;
$$;

-- 3. Validasi Token QR Meja (Token salah atau kedai nonaktif ditolak)
create or replace function public.validate_table_qr(
    p_cafe_id text,
    p_table_number text,
    p_qr_token text
)
returns boolean
language sql
security definer
stable
set search_path = public, pg_temp
as $$
    select exists (
        select 1
        from public.tables t
        join public.cafes c on c.id = t.cafe_id
        where t.cafe_id = p_cafe_id
          and t.table_number = p_table_number
          and t.qr_token = p_qr_token
          and t.is_active = true
          and c.is_active = true
    );
$$;

-- 4. Pembatasan Jumlah Pesanan Per Perangkat/Meja (Mencegah Pesanan Iseng)
create or replace function public.check_order_rate_limit(
    p_cafe_id text,
    p_table_number text,
    p_device_id text
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_active_count integer;
begin
    select count(*) into v_active_count
    from public.orders
    where cafe_id = p_cafe_id
      and status in ('baru', 'diproses')
      and (
          (p_device_id is not null and device_id = p_device_id)
          or (table_number = p_table_number)
      )
      and created_at > (now() - interval '1 hour');

    -- Maksimal 3 pesanan aktif yang belum selesai per meja/perangkat
    return (v_active_count < 3);
end;
$$;

