-- 4. Security Definer functions hardened with 'set search_path = public, pg_temp'.
-- 5. Timestamptz (timezone-aware) & standard identity columns.
-- 6. Storage Bucket CRUD lengkap (SELECT, INSERT, UPDATE upsert, DELETE).
-- 7. Realtime publications aman & replica identity full.

